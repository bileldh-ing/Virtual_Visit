/**
 * Trust layer for explorable worlds: what is captured, what is inferred, what is not claimed. Pure, unit-tested.
 */

export type Honesty = "ai_generated" | "depth_estimated" | "reconstructed" | "captured";
export type TrustRow = { key: string; label: string; status: "captured" | "inferred" | "estimated" | "not claimed"; detail: string };

export const BADGE: Record<Honesty, { text: string; tone: "amber" | "sky" | "teal" }> = {
  ai_generated: { text: "AI-generated world — areas may be inferred", tone: "amber" },
  depth_estimated: { text: "Depth-estimated room — lower fidelity", tone: "sky" },
  reconstructed: { text: "Reconstructed from photos", tone: "teal" },
  captured: { text: "Captured panoramas", tone: "teal" },
};

export function trustRows(opts: {
  honesty: Honesty;
  photos: number;
  placedPhotos: number;
  hasCollider: boolean;
  metric: boolean;
  engineLabel?: string;
  depthModel?: string;
}): TrustRow[] {
  const { honesty, photos, placedPhotos } = opts;
  const rows: TrustRow[] = [
    {
      key: "photos",
      label: "Your photos",
      status: "captured",
      detail: `${photos} original photo${photos === 1 ? "" : "s"}, unmodified and viewable at any time.${placedPhotos ? ` ${placedPhotos} shown at their viewpoint${placedPhotos === 1 ? "" : "s"}.` : ""}`,
    },
  ];
  if (honesty === "ai_generated") {
    rows.push({
      key: "world",
      label: "The 3D world",
      status: "inferred",
      detail: `Generated by ${opts.engineLabel ?? "a generative world model"} from your photos. Surfaces the photos never showed (behind furniture, other rooms, ceilings) were filled in by the model and may not match the property.`,
    });
  } else if (honesty === "depth_estimated") {
    rows.push({
      key: "world",
      label: "The 3D room",
      status: "estimated",
      detail: `Each photo's depth was predicted by ${opts.depthModel ?? "a monocular depth model"} and stitched at the solved camera positions. Shapes are approximate; nothing beyond the photos was added.`,
    });
  } else {
    rows.push({ key: "world", label: "Geometry", status: "captured", detail: "Measured from your photos." });
  }
  rows.push({
    key: "collision",
    label: "Walls & floor for walking",
    status: opts.hasCollider ? (honesty === "ai_generated" ? "inferred" : "estimated") : "not claimed",
    detail: opts.hasCollider
      ? "A collision mesh keeps you inside the space; it follows the generated/estimated surfaces, not a survey."
      : "No collision mesh: you can only move between known viewpoints.",
  });
  rows.push({
    key: "scale",
    label: "Dimensions",
    status: "not claimed",
    detail: opts.metric
      ? "The provider estimates a metric scale, but it is not a measurement. Measuring is disabled."
      : "Scale is relative. Measuring is disabled; no dimensions are claimed.",
  });
  return rows;
}

export function measurementTooltip(honesty: Honesty): string {
  return honesty === "ai_generated"
    ? "Measurement disabled: AI-generated geometry is not reliable for dimensions."
    : "Measurement disabled: depth is estimated per photo, so dimensions are not reliable.";
}

/**
 * Which captured photo (if any) covers the current view. A photo covers the view when the camera is near where it was
 * taken (within `maxDist` on the floor plane) and looks within `halfAngleDeg` of the photo's heading. Anything else is
 * a part of the world no photo showed: for generated worlds that is inferred content and the viewer labels it so.
 */
export function coveringPhoto(
  view: { x: number; z: number; yaw: number },
  shots: { p: [number, number, number]; yaw: number }[],
  halfAngleDeg = 35,
  maxDist = 1.5,
): number | null {
  let best: number | null = null;
  let bestA = Infinity;
  shots.forEach((s, i) => {
    if (Math.hypot(s.p[0] - view.x, s.p[2] - view.z) > maxDist) return;
    const d = Math.abs(Math.atan2(Math.sin(view.yaw - s.yaw), Math.cos(view.yaw - s.yaw)));
    if (d <= (halfAngleDeg * Math.PI) / 180 && d < bestA) {
      bestA = d;
      best = i;
    }
  });
  return best;
}
