ARTIFACT_SCHEMA_VERSION = "1.0"
WEB_POINT_BUDGET = 400_000  # max points in the web-optimised PLY


def safe_child(root: Path, name: str) -> Path:
    """Resolve ``name`` under ``root`` and refuse anything that escapes it."""
    root = root.resolve()
    candidate = (root / name).resolve()
    if candidate != root and root not in candidate.parents:
        raise ReconError(ErrorCategory.INVALID_INPUT, "Invalid file name.", f"path escape: {name!r}")
    return candidate


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


# ---------------------------------------------------------------- PLY

def write_ply(path: Path, xyz: np.ndarray, rgb: np.ndarray) -> None:
    n = int(xyz.shape[0])
    header = (
        "ply\nformat binary_little_endian 1.0\n"
        "comment generated by roomscape-recon from a COLMAP sparse model\n"
        f"element vertex {n}\n"
        "property float x\nproperty float y\nproperty float z\n"
        "property uchar red\nproperty uchar green\nproperty uchar blue\n"
        "end_header\n"
    ).encode("ascii")
    rec = np.empty(n, dtype=[("x", "<f4"), ("y", "<f4"), ("z", "<f4"), ("r", "u1"), ("g", "u1"), ("b", "u1")])
    rec["x"], rec["y"], rec["z"] = xyz[:, 0], xyz[:, 1], xyz[:, 2]
    rec["r"], rec["g"], rec["b"] = rgb[:, 0], rgb[:, 1], rgb[:, 2]
    with path.open("wb") as fh:
        fh.write(header)
        fh.write(rec.tobytes())


@dataclass
class PlyInfo:
    vertex_count: int
    face_count: int
    fmt: str
    properties: list[str]


def validate_ply(path: Path, expect_faces: bool = False) -> PlyInfo:
    """Parse the PLY header and check that the payload size matches."""
    if not path.is_file() or path.stat().st_size == 0:
        raise ReconError(ErrorCategory.ARTIFACT_INVALID, "Point cloud artifact is missing or empty.")
    with path.open("rb") as fh:
        if fh.readline().strip() != b"ply":
            raise ReconError(ErrorCategory.ARTIFACT_INVALID, "Artifact is not a PLY file.")
        fmt = ""
        verts = faces = 0
        props: list[str] = []
        current = None
        sizes = {"float": 4, "uchar": 1, "double": 8, "int": 4, "uint": 4, "short": 2, "ushort": 2, "char": 1}
        vert_bytes = 0
        while True:
            line = fh.readline()
            if not line:
                raise ReconError(ErrorCategory.ARTIFACT_INVALID, "PLY header is truncated.")
            tok = line.decode("ascii", "replace").split()
            if not tok:
                continue
            if tok[0] == "format":
                fmt = tok[1]
            elif tok[0] == "element":
                current = tok[1]
                if current == "vertex":
                    verts = int(tok[2])
                elif current == "face":
                    faces = int(tok[2])
            elif tok[0] == "property" and current == "vertex":
                props.append(tok[-1])
                vert_bytes += sizes.get(tok[1], 0)
            elif tok[0] == "end_header":
                header_len = fh.tell()
                break
    if verts <= 0:
        raise ReconError(ErrorCategory.ARTIFACT_INVALID, "Point cloud has no vertices.")
    if expect_faces and faces <= 0:
        raise ReconError(ErrorCategory.ARTIFACT_INVALID, "Mesh has no faces.")
    if fmt == "binary_little_endian" and faces == 0:
        expected = header_len + verts * vert_bytes
        if path.stat().st_size != expected:
            raise ReconError(ErrorCategory.ARTIFACT_INVALID, "PLY payload size does not match its header.")
    return PlyInfo(verts, faces, fmt, props)


# ---------------------------------------------------------------- viewer metadata

def estimate_up(model: SparseModel) -> np.ndarray:
    """Estimate world 'up' as the mean of camera up vectors (image -Y axis).

    This is an estimate: it assumes photos were taken roughly upright, which is
    typical for property capture. It is labelled as such in the metadata.
    """
    ups = []
    for im in model.images.values():
        r = im.rotation()
        ups.append(r.T @ np.array([0.0, -1.0, 0.0]))
    if not ups:
        return np.array([0.0, 1.0, 0.0])
    v = np.mean(ups, axis=0)
    n = np.linalg.norm(v)
    return v / n if n > 1e-9 else np.array([0.0, 1.0, 0.0])


def _align_rotation(up: np.ndarray) -> np.ndarray:
    """Rotation that maps ``up`` onto +Y."""
    target = np.array([0.0, 1.0, 0.0])
    v = np.cross(up, target)
    c = float(np.dot(up, target))
    if np.linalg.norm(v) < 1e-9:
        return np.eye(3) if c > 0 else np.diag([1.0, -1.0, -1.0])
    vx = np.array([[0, -v[2], v[1]], [v[2], 0, -v[0]], [-v[1], v[0], 0]])
    return np.eye(3) + vx + vx @ vx * (1.0 / (1.0 + c))


def filter_for_web(model: SparseModel) -> tuple[np.ndarray, np.ndarray, dict]:
    """Drop far outliers (beyond the 98th percentile distance) and cap point count."""
    xyz, rgb = model.xyz, model.rgb
    if len(xyz) == 0:
        return xyz, rgb, {"input_points": 0, "kept_points": 0}
    med = np.median(xyz, axis=0)
    d = np.linalg.norm(xyz - med, axis=1)
    keep = d <= np.percentile(d, 98)
    xyz2, rgb2 = xyz[keep], rgb[keep]
    if len(xyz2) > WEB_POINT_BUDGET:
        idx = np.random.default_rng(0).choice(len(xyz2), WEB_POINT_BUDGET, replace=False)
        xyz2, rgb2 = xyz2[idx], rgb2[idx]
    return xyz2, rgb2, {"input_points": int(len(xyz)), "kept_points": int(len(xyz2)), "outlier_percentile": 98}


def build_viewer_metadata(model: SparseModel, image_map: dict[str, str] | None = None) -> dict:
    """cameras.json: registered viewpoints and a viewer transform (estimated up)."""
    up = estimate_up(model)
    align = _align_rotation(up)
    centers = np.array([im.center() for im in model.images.values()]) if model.images else np.zeros((0, 3))
    pts = model.xyz if len(model.xyz) else centers
    origin = np.median(pts, axis=0) if len(pts) else np.zeros(3)
    aligned = (pts - origin) @ align.T if len(pts) else pts
    extent = float(np.percentile(np.linalg.norm(aligned, axis=1), 95)) if len(aligned) else 1.0
    viewpoints = []
    for im in sorted(model.images.values(), key=lambda i: i.name):
        cam = model.cameras[im.camera_id]
        r = im.rotation()
        focal = cam.params[0] if cam.params else None
        viewpoints.append({
            "image_id": im.image_id,
            "name": im.name,
            "upload_id": (image_map or {}).get(im.name),
            "position": [float(v) for v in im.center()],
            # camera-to-world rotation (columns: camera x, y, z axes in world)
            "rotation_c2w": [[float(v) for v in row] for row in r.T],
            "width": cam.width,
            "height": cam.height,
            "focal_px": focal,
            "camera_model": cam.model,
            "observations": im.num_points2d,
        })
    return {
        "schema": ARTIFACT_SCHEMA_VERSION,
        "coordinate_system": "COLMAP world (right-handed, arbitrary origin)",
        "scale": "unknown",
        "scale_note": "Monocular reconstruction: distances are relative, not metres.",
        "up_estimate": [float(v) for v in up],
        "up_estimate_method": "mean camera up-vector (assumes upright photos)",
        "viewer_transform": {
            "origin": [float(v) for v in origin],
            "rotation": [[float(v) for v in row] for row in align],
            "extent": extent,
        },
        "viewpoints": viewpoints,
    }


def render_preview(model: SparseModel, meta: dict, path: Path, size: int = 768) -> None:
    """Top-down orthographic preview of the actual sparse points and cameras."""
    tr = meta["viewer_transform"]
    origin = np.asarray(tr["origin"])
    rot = np.asarray(tr["rotation"])
    img = Image.new("RGB", (size, size), (14, 20, 28))
    draw = ImageDraw.Draw(img)
    if len(model.xyz):
        a = (model.xyz - origin) @ rot.T
        ext = max(tr["extent"], 1e-6) * 1.15
        u = ((a[:, 0] / ext) * 0.5 + 0.5) * size
        v = ((a[:, 2] / ext) * 0.5 + 0.5) * size
        ok = (u >= 0) & (u < size) & (v >= 0) & (v < size)
        arr = np.asarray(img).copy()
        arr[v[ok].astype(int), u[ok].astype(int)] = model.rgb[ok]
        img = Image.fromarray(arr)
        draw = ImageDraw.Draw(img)
        for vp in meta["viewpoints"]:
            c = (np.asarray(vp["position"]) - origin) @ rot.T
            cu, cv = (c[0] / ext * 0.5 + 0.5) * size, (c[2] / ext * 0.5 + 0.5) * size
            draw.ellipse([cu - 3, cv - 3, cu + 3, cv + 3], fill=(45, 212, 191))
    img.save(path, format="PNG", optimize=True)


# ---------------------------------------------------------------- manifest

MIME = {".ply": "application/ply", ".json": "application/json", ".png": "image/png", ".jpg": "image/jpeg",
        ".txt": "text/plain", ".log": "text/plain", ".glb": "model/gltf-binary", ".splat": "application/octet-stream"}


def build_manifest(out_dir: Path, entries: list[dict], engine: dict) -> dict:
    files = []
    for e in entries:
        p = safe_child(out_dir, e["path"])
        files.append({
            **e,
            "bytes": p.stat().st_size,
            "sha256": sha256_file(p),
            "mime": MIME.get(p.suffix.lower(), "application/octet-stream"),
        })
    manifest = {
        "schema": ARTIFACT_SCHEMA_VERSION,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "engine": engine,
        "access_policy": "private",
        "artifacts": files,
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2))
    return manifest


def verify_manifest(out_dir: Path) -> list[str]:
    """Re-hash every artifact listed in manifest.json. Returns a list of problems."""
    problems = []
    manifest = json.loads((out_dir / "manifest.json").read_text())
    for f in manifest["artifacts"]:
        try:
            p = safe_child(out_dir, f["path"])
        except ReconError:
            problems.append(f"{f['path']}: escapes artifact directory")
            continue
        if not p.is_file():
            problems.append(f"{f['path']}: missing")
        elif p.stat().st_size != f["bytes"] or sha256_file(p) != f["sha256"]:
            problems.append(f"{f['path']}: checksum mismatch")
    return problems


def ply_header_bytes(n: int) -> int:  # pragma: no cover - helper for docs/tests
    return len(struct.pack("<fff", 0, 0, 0)) * n
